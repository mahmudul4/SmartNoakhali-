export const BUILTIN_CATEGORY_ICON_ITEMS: BuiltInCategoryIconItem[] =
  BUILTIN_CATEGORY_ICON_FILENAMES.map((filename) => {
    const slug = filename.replace(/\.png$/i, "");
    return {
      slug,
      filename,
      url: `/icons/categories/${filename}`,
    };
  });

export const BUILTIN_CATEGORY_ICON_MAP: Record<string, string> =
  Object.fromEntries(BUILTIN_CATEGORY_ICON_ITEMS.map((item) => [item.slug, item.url]));

export function getBuiltInCategoryIconUrl(slug: string): string | undefined {
  const normalized = String(slug || "").trim().toLowerCase();
  return BUILTIN_CATEGORY_ICON_MAP[normalized];
}
